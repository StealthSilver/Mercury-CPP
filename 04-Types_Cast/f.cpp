#include <iostream>
using namespace std;

int main()
{

    int a = 5;

    int b = 3;

    cout << "+ : " << (a + b) << endl; // addition
    cout << "- : " << (a - b) << endl; // substraction
    cout << "* : " << (a * b) << endl; // multiplication
    cout << "/ : " << (a / b) << endl; // division
    cout << "% : " << (a % b) << endl; // modulus

    return 0;
}